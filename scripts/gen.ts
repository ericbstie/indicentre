// Regenerates the registry index files (src/apps, src/scams, src/systems).
// A registry entry is any .ts file in the folder with a default export.
//   bun run gen          rewrite the indexes
//   bun run gen --check  fail if an index is stale (used by `bun run check`)
import { readdirSync } from "node:fs";
import { join } from "node:path";

interface Registry {
  readonly dir: string;
  readonly typeName: string;
  readonly typeFrom: string;
  readonly exportName: string;
}

export const REGISTRIES: ReadonlyArray<Registry> = [
  {
    dir: "src/apps",
    typeName: "DesktopApp",
    typeFrom: "./app.ts",
    exportName: "apps",
  },
  {
    dir: "src/scams",
    typeName: "ScamDef",
    typeFrom: "./types.ts",
    exportName: "allScams",
  },
  {
    dir: "src/systems",
    typeName: "GameSystem",
    typeFrom: "./system.ts",
    exportName: "systems",
  },
];

const ident = (file: string) =>
  file
    .replace(/\.ts$/, "")
    .replace(/[-_.](\w)/g, (_, c: string) => c.toUpperCase());

const render = async (r: Registry) => {
  const files: string[] = [];
  for (const f of readdirSync(r.dir).sort()) {
    if (!f.endsWith(".ts") || f === "index.ts" || f.endsWith(".test.ts"))
      continue;
    if (/^export default /m.test(await Bun.file(join(r.dir, f)).text()))
      files.push(f);
  }
  return [
    "// Generated by `bun run gen` from the files in this folder. Do not edit.",
    `import type { ${r.typeName} } from "${r.typeFrom}";`,
    ...files.map((f) => `import ${ident(f)} from "./${f}";`),
    "",
    `export const ${r.exportName}: ReadonlyArray<${r.typeName}> = [${files.map(ident).join(", ")}];`,
    "",
  ].join("\n");
};

/** Formats generated source exactly as `bun fmt` would, so --check is stable. */
const fmt = async (path: string, source: string) => {
  const proc = Bun.spawn(
    ["bun", "fmt", "--no-script", `--stdin-filepath=${path}`],
    { stdin: new Blob([source]), stdout: "pipe" },
  );
  const out = await new Response(proc.stdout).text();
  if ((await proc.exited) !== 0) throw new Error(`bun fmt failed on ${path}`);
  return out;
};

export const gen = async (check = false) => {
  let stale = 0;
  for (const r of REGISTRIES) {
    const path = join(r.dir, "index.ts");
    const file = Bun.file(path);
    const next = await fmt(path, await render(r));
    const current = (await file.exists()) ? await file.text() : "";
    if (current === next) continue;
    if (check) {
      console.error(`${path} is stale: run \`bun run gen\``);
      stale++;
    } else await Bun.write(path, next);
  }
  if (stale) process.exit(1);
};

if (import.meta.main) await gen(process.argv.includes("--check"));
